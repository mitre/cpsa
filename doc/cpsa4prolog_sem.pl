% sat(s,eta,Form)

% F, s |=_eta Form


query(F,Res) :- findall(S,sat(S,[],F),Res).


sat(S,_,tt) :- skel(S).
sat(_,_,ff) :- fail.


sat(S, shape) :- shape(S).
sat(S, dead) :- dead(S).


sat(S, Eta, not(F)) :- \+ sat(S, Eta, F).

sat(S, Eta, and([])) :- sat(S, Eta, tt).
sat(S, Eta, and([F|FS])) :- sat(S, Eta, F), sat(S, Eta, and(FS)).

sat(S, Eta, or([])) :- sat(S, Eta, ff).
sat(S, Eta, or([F|_])) :- sat(S, Eta, F).
sat(S, Eta, or([_|FS])) :- sat(S, Eta, or(FS)).



sat(S, Eta1, diam(A, F)) :- step(S, Step, T), stepSat(Step, A), etwa(Eta, Step, Eta2) sat(T, Eta, F).

sat(S, Eta, diam(test(T), F)) :- sat(S, Eta, and([T,F])).

sat(S, Eta, diam(cat([]), F)) :- sat(S, Eta, F).
sat(S, Eta, diam(cat([A|AS]), F)) :- sat(S, Eta, diam(A, diam(cat(AS), F))).

sat(_, Eta, diam(cup([]), _)) :- fail.
sat(S, Eta, diam(cup([A|AS]), F)) :- sat(S, Eta, or([diam(A, F), diam(cup(AS), F)])).

sat(S, Eta, diam(star(A), F)) :- sat(S, Eta, or([F, diam(A, diam(star(A), F))])).

sat(S, Eta, diam(plus(A), F)) :- sat(S, Eta, diam(cat([A, star(A)]), F)).


sat(S, Eta, box(A, F)) :- sat(S, Eta, not(diam(A, not(F)))).




stepSat(_, dot).
stepSat(Step, encryption_test) :- encryption-test(Step,_,_,_).
stepSat(Step, nonce_test) :- nonce-test(Step,_,_,_,_,_,_).
stepSat(Step, generalization(Type)) :- generalization(Step,Type,_).


